#!/bin/sh
# Builds kaggle/ft_llm_text/kernel.py: Qwen2.5-7B-Instruct QLoRA regression on transcripts (src/ft_llm_text.py),
# folds 0/2/4 on GPU 0 and 1/3 on GPU 1. The kernel embeds the transcripts, so it is gitignored.
cd "$(dirname "$0")/.."
B64=$(base64 < src/ft_llm_text.py | tr -d '\n')
FOLDS=$(base64 < cache/folds_grouped_r0.csv | tr -d '\n')
TXT=$(.venv/bin/python -c "
import json
r=[json.loads(l) for l in open('cache/transcripts.jsonl')]
print(json.dumps([dict(split=x['split'],filename=x['filename'],text=' '.join(s['text'].strip() for s in x['segments']).strip() or '.') for x in r]))" | gzip | base64 | tr -d '\n')
cat > kaggle/ft_llm_text/kernel.py <<PY
# Kaggle kernel: Qwen2.5-7B QLoRA on transcripts. Generated by kaggle/build_ft_llm_text.sh from src/ft_llm_text.py.
import base64, glob, gzip, os, subprocess, sys, threading, time
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U", "bitsandbytes"], check=True)
import torch
from huggingface_hub import snapshot_download
OUT = "/kaggle/working/ft_llm_text"
open("/tmp/ft_llm_text.py", "w").write(base64.b64decode("$B64").decode())
open("/tmp/folds.csv", "w").write(base64.b64decode("$FOLDS").decode())
open("/tmp/texts.json", "wb").write(gzip.decompress(base64.b64decode("$TXT")))
DATA = os.path.dirname(glob.glob("/kaggle/input/**/train.csv", recursive=True)[0])
snapshot_download("Qwen/Qwen2.5-7B-Instruct")
n = max(1, torch.cuda.device_count())
print("GPUs:", n, [torch.cuda.get_device_name(i) for i in range(n)], flush=True)
queues = [[k for k in range(5) if k % n == g] for g in range(n)]
codes, t0 = {}, time.time()

def run_queue(g):
    for k in queues[g]:
        r = subprocess.run([sys.executable, "/tmp/ft_llm_text.py", "--texts", "/tmp/texts.json", "--data", DATA,
                            "--folds", "/tmp/folds.csv", "--out", OUT, "--fold", str(k), "--epochs", "2"],
                           env={**os.environ, "CUDA_VISIBLE_DEVICES": str(g)})
        codes[k] = r.returncode

th = [threading.Thread(target=run_queue, args=(g,)) for g in range(n)]
[t.start() for t in th]; [t.join() for t in th]
print("fold exit codes:", codes, "| wall time %.0f min" % ((time.time() - t0) / 60), flush=True)
os.remove("/tmp/texts.json")
PY
echo "built kaggle/ft_llm_text/kernel.py"
