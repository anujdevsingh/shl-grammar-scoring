#!/bin/sh
# Round 4 of the Whisper adapter grader: round-3 setup (pseudo-labels) + per-clip normalisation of the frames.
# Extract Whisper frames once on GPU 0; then GPU 0 trains the mean+variance variant and GPU 1 the mean-only variant,
# each on all 5 folds x 3 seeds, in parallel.
cd "$(dirname "$0")/.."
B64=$(base64 < src/adapter.py | tr -d '\n')
FOLDCSV=$(cut -d, -f1,2 cache/folds.csv | base64 | tr -d '\n')
PSEUDO=$(cd cache/pseudo && COPYFILE_DISABLE=1 tar cz pseudo_fold*.csv | base64 | tr -d '\n')
cat > kaggle/adapter4/kernel.py <<PY
# Kaggle kernel for Stage J round 4 (per-clip normalised adapter). Generated by kaggle/build_adapter4.sh.
import base64, glob, io, os, subprocess, sys, tarfile, threading, time
import torch
from huggingface_hub import snapshot_download

OUT, TMP = "/kaggle/working", "/tmp/frames"
open("/tmp/adapter.py", "w").write(base64.b64decode("$B64").decode())
open("/tmp/folds.csv", "w").write(base64.b64decode("$FOLDCSV").decode())
tarfile.open(fileobj=io.BytesIO(base64.b64decode("$PSEUDO"))).extractall("/tmp/pseudo", filter="data")
DATA = os.path.dirname(glob.glob("/kaggle/input/**/train.csv", recursive=True)[0])
snapshot_download("openai/whisper-large-v3", allow_patterns=["*.json", "*.safetensors", "*.txt"])
n = torch.cuda.device_count()
print("GPUs:", n, [torch.cuda.get_device_name(i) for i in range(n)], "| pseudo files", sorted(os.listdir("/tmp/pseudo")), flush=True)
py = [sys.executable, "/tmp/adapter.py"]
t0 = time.time()
r = subprocess.run(py + ["extract", "--data", DATA, "--out", TMP, "--encoder", "whisper"],
                   env={**os.environ, "CUDA_VISIBLE_DEVICES": "0"})
assert r.returncode == 0
codes = {}

def train(cmvn, gpu):
    r = subprocess.run(py + ["train", "--feats", TMP, "--data", DATA, "--folds", "/tmp/folds.csv",
                             "--out", f"{OUT}/adapter4{cmvn}_whisper", "--encoder", "whisper", "--folds_to_run", "0,1,2,3,4",
                             "--seeds", "3", "--pseudo_dir", "/tmp/pseudo", "--pseudo_w", "0.5", "--cmvn", cmvn],
                       env={**os.environ, "CUDA_VISIBLE_DEVICES": str(gpu)})
    codes[cmvn] = r.returncode

th = [threading.Thread(target=train, args=j) for j in [("meanvar", 0), ("mean", 1 % max(1, n))]]
[t.start() for t in th]; [t.join() for t in th]
print("train exit codes:", codes, "| wall time %.0f min" % ((time.time() - t0) / 60), flush=True)
PY
echo "built kaggle/adapter4/kernel.py"
