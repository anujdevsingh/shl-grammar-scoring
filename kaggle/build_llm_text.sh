#!/bin/sh
# Builds kaggle/llm_text/kernel.py: LLM hidden states of the transcripts (src/llm_text_emb.py), one model per GPU:
# GPU 0 Qwen2.5-7B-Instruct in 4-bit, GPU 1 Qwen3-4B in fp16. The kernel embeds the transcripts, so it is gitignored.
cd "$(dirname "$0")/.."
B64=$(base64 < src/llm_text_emb.py | tr -d '\n')
TXT=$(.venv/bin/python -c "
import json
r=[json.loads(l) for l in open('cache/transcripts.jsonl')]
print(json.dumps([dict(split=x['split'],filename=x['filename'],text=' '.join(s['text'].strip() for s in x['segments']).strip() or '.') for x in r]))" | gzip | base64 | tr -d '\n')
cat > kaggle/llm_text/kernel.py <<PY
# Kaggle kernel: LLM text embeddings. Generated by kaggle/build_llm_text.sh from src/llm_text_emb.py.
import base64, gzip, os, subprocess, sys, threading, time
subprocess.run([sys.executable, "-m", "pip", "install", "-q", "-U", "bitsandbytes"], check=True)
import torch
open("/tmp/llm_text_emb.py", "w").write(base64.b64decode("$B64").decode())
open("/tmp/texts.json", "wb").write(gzip.decompress(base64.b64decode("$TXT")))
n = torch.cuda.device_count()
print("GPUs:", n, [torch.cuda.get_device_name(i) for i in range(n)], flush=True)
jobs = [("Qwen/Qwen2.5-7B-Instruct", ["--4bit"], 0), ("Qwen/Qwen3-4B", [], 1 % max(1, n))]
codes, t0 = {}, time.time()

def run(model, extra, gpu):
    r = subprocess.run([sys.executable, "/tmp/llm_text_emb.py", "--texts", "/tmp/texts.json", "--out", "/kaggle/working/llm_text",
                        "--model", model, *extra], env={**os.environ, "CUDA_VISIBLE_DEVICES": str(gpu)})
    codes[model] = r.returncode

th = [threading.Thread(target=run, args=j) for j in jobs]
[t.start() for t in th]; [t.join() for t in th]
print("exit codes:", codes, "| wall time %.0f min" % ((time.time() - t0) / 60), flush=True)
os.remove("/tmp/texts.json")
PY
echo "built kaggle/llm_text/kernel.py"
